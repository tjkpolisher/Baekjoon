# 18310: 안테나
# 알고리즘 분류: 수학/그리디 알고리즘/정렬

# 1. 집의 수 N 입력 (1 ≤ N ≤ 200,000)
# 2. N채의 집의 위치가 공백으로 구분되어 한 줄에 입력
# [보충설명] 집의 위치는 1 이상 100,000 이하의 자연수
# [보충설명] 동일한 위치에 여러 개의 집이 존재할 수 있음
# 3. 입력받은 집의 위치를 오름차순으로 정렬
# 4. 중간값을 출력

N = int(input())
house = list(map(int, input().split()))
house.sort()
print(house[(N - 1) // 2])
